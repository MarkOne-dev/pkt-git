"""pkt-git global CLI hub.

Installed once per machine by install.sh / install.ps1 (command: `pkt`,
legacy alias `ptg`); used by thin repository hooks generated by
`pkt init`. Subcommands:

    pkt init [dir]                wire hooks into any repository (no templates)
    pkt export build inspect      see tools/ptg.py
    pkt edit ...                  see tools/edit_config.py
    pkt verify / sync             verification and snapshot consistency
    pkt pre-commit                thin-hook entry (do not call manually)
    pkt post-merge [old new]      thin-hook entry (do not call manually)
    pkt post-checkout [old new]   thin-hook entry (do not call manually)
    pkt --version
"""

import json
import os
import subprocess
import sys
from pathlib import Path

_TOOLS = Path(__file__).resolve().parent
sys.path.insert(0, str(_TOOLS))

import edit_config as _edit  # noqa: E402
import ptg as _ptg  # noqa: E402
import spike_roundtrip as _codec  # noqa: E402

HOOK_DIR = ".githooks"
HOOKS = {
    "pre-commit": (
        "#!/usr/bin/env bash\n"
        "# Thin hook generated by `pkt init` (pkt-git).\n"
        '# Requires the pkt-git CLI installed (`pkt --version`).\n'
        'exec "$(git config --get pktgit.py)" "$(git config --get pktgit.script)" pre-commit\n'
    ),
    "post-merge": (
        "#!/usr/bin/env bash\n"
        "# Thin hook generated by `pkt init` (pkt-git).\n"
        'exec "$(git config --get pktgit.py)" "$(git config --get pktgit.script)" post-merge "$@"\n'
    ),
    "post-checkout": (
        "#!/usr/bin/env bash\n"
        "# Thin hook generated by `pkt init` (pkt-git).\n"
        'exec "$(git config --get pktgit.py)" "$(git config --get pktgit.script)" post-checkout "$@"\n'
    ),
}


def _git(*args: str) -> str:
    """Run git and return stdout; abort with git's stderr on failure."""
    proc = subprocess.run(["git", *args], capture_output=True, text=True)
    if proc.returncode != 0:
        raise SystemExit(f"[pkt-git] git {' '.join(args)} failed: {proc.stderr.strip()}")
    return proc.stdout


def _export_snapshot(pkt: Path) -> Path:
    """Export <pkt> into snapshot/<stem>/ and return that directory."""
    out = Path("snapshot") / pkt.stem
    _ptg.cmd_export(pkt, out)
    return out


def cmd_export(args: list[str]) -> int:
    """Export a .pkt into its textual snapshot."""
    return _ptg.cmd_export(Path(args[0]), Path(args[1]))


def cmd_build(args: list[str]) -> int:
    """Rebuild a binary .pkt from a snapshot XML."""
    return _ptg.cmd_build(Path(args[0]), Path(args[1]))


def cmd_inspect(args: list[str]) -> int:
    """Print a topology summary for a .pkt."""
    return _ptg.cmd_inspect(Path(args[0]))


def _sync_snapshot(xml_path: Path) -> None:
    """Refresh configs/*.cfg and metadata/topology.json from a snapshot XML."""
    if not xml_path.name == "base.snapshot.xml" or not xml_path.parent.exists():
        return
    proj = xml_path.parent
    if not (proj / "metadata" / "topology.json").exists():
        return
    devices, links = _ptg.parse_topology(xml_path.read_text(encoding="utf-8"))
    cfgdir = proj / "configs"
    cfgdir.mkdir(exist_ok=True)
    for dev in devices:
        if dev.runningconfig:
            (cfgdir / f"{_ptg.sanitize(dev.name)}.cfg").write_text(
                "\n".join(dev.runningconfig) + "\n", encoding="utf-8")
    catalog = json.loads((proj / "metadata" / "topology.json").read_text(encoding="utf-8"))
    catalog["total_devices"] = len(devices)
    catalog["total_links"] = len(links)
    (proj / "metadata" / "topology.json").write_text(
        json.dumps(catalog, indent=2, ensure_ascii=False), encoding="utf-8")


def cmd_edit(args: list[str]) -> int:
    """Forward to tools/edit_config.py; keep derived configs in sync."""
    xml_path = Path(args[0])
    sys.argv = ["edit_config"] + args
    code = _edit.main()
    if code == 0:
        _sync_snapshot(xml_path)
    return code


def cmd_sync(args: list[str]) -> int:
    """Regenerate configs/*.cfg and topology.json from a snapshot XML."""
    xml_path = Path(args[0]) / "base.snapshot.xml" if Path(args[0]).is_dir() else Path(args[0])
    _sync_snapshot(xml_path)
    print(f"[ok] configs and metadata refreshed from {xml_path}")
    return 0



def cmd_verify(args: list[str]) -> int:
    """Round-trip verification of a .pkt specimen."""
    return _codec.cmd_verify(Path(args[0]), Path("out"))


def cmd_pre_commit(args: list[str]) -> int:
    """Export and stage the snapshot of every staged .pkt; warn on text-only edits."""
    _git("rev-parse", "--show-toplevel")
    staged = [f for f in _git(
        "diff", "--cached", "--name-only", "--diff-filter=ACMR", "--", "*.pkt"
    ).splitlines() if f]

    for f in staged:
        print(f"[pre-commit] .pkt changed: {f} -> exporting snapshot to snapshot/{Path(f).stem}/")
        try:
            out = _export_snapshot(Path(f))
        except SystemExit:
            raise
        except Exception as exc:
            raise SystemExit(f"[pre-commit] ERROR exporting {f}: {exc}")
        _git("add", "--", str(out))

    if not staged:
        txt = _git(
            "diff", "--cached", "--name-only", "--diff-filter=MCR",
            "--", "snapshot/*/base.snapshot.xml",
        ).strip()
        if txt:
            print("[pre-commit] Warning: textual snapshot changed without its .pkt.")
            print("  Valid (textual edit/merge); rebuild the binary before opening PT:")
            print("    pkt build snapshot/<project>/base.snapshot.xml topologia/<project>.pkt")
    elif staged:
        print("[pre-commit] textual snapshot included automatically.")
    return 0


def cmd_post_merge_checkout(args: list[str]) -> int:
    """Rebuild topologia/<project>.pkt for snapshots changed by merge/pull/checkout."""
    _git("rev-parse", "--show-toplevel")
    old, new = (args + [None, None])[:2]

    if old and set(old) != {"0"}:
        rng = [old, new]
    else:
        rng = ["ORIG_HEAD", "HEAD"]

    files = [
        f for f in _git(
            "diff", "--name-only", *rng, "--", "snapshot/*/base.snapshot.xml",
        ).splitlines() if f
    ]
    for xml in files:
        proj = Path(xml).parts[-2]
        pkt = Path("topologia") / f"{proj}.pkt"
        print(f"[pkt-git] snapshot of '{proj}' updated by merge/checkout. Rebuilding {pkt} ...")
        pkt.parent.mkdir(parents=True, exist_ok=True)
        try:
            _ptg.cmd_build(Path(xml), pkt)
        except Exception as exc:
            print(f"[pkt-git] ERROR rebuilding {pkt}: {exc} — inspect snapshot/ manually.")
            continue
        print(f"[pkt-git] '{pkt}' rebuilt — open it in Packet Tracer.")
    return 0


def cmd_post_merge(args: list[str]) -> int:
    """Thin-hook entry after a pull/merge."""
    return cmd_post_merge_checkout(args)


def cmd_post_checkout(args: list[str]) -> int:
    """Thin-hook entry after a branch switch."""
    return cmd_post_merge_checkout(args)


def cmd_init(args: list[str]) -> int:
    """Wire pkt-git into a repository: thin hooks + per-repo CLI config."""
    root = Path(args[0]) if args else Path(".")
    os.chdir(root)

    try:
        _git("rev-parse", "--git-dir")
    except SystemExit:
        print("[pkt-git] not a git repository — run `git init` first.", file=sys.stderr)
        return 2

    py = os.environ.get("PKTG_PY") or sys.executable
    script = os.environ.get("PKTG_SCRIPT") or str(Path(sys.argv[0]).resolve())
    if not Path(script).name == "cli.py":
        script = str(_TOOLS / "cli.py")

    hookdir = Path(HOOK_DIR)
    hookdir.mkdir(exist_ok=True)
    for name, body in HOOKS.items():
        hook = hookdir / name
        hook.write_text(body, encoding="utf-8")
        hook.chmod(0o755)

    attrs = Path(".gitattributes")
    if not attrs.exists():
        attrs.write_text(
            "\n".join([
                "# pkt-git ownership: the binary is an artifact; the snapshot is the source of truth.",
                "*.pkt binary",
                "snapshot/**/base.snapshot.xml text",
                "snapshot/**/*.json text",
                "snapshot/**/*.cfg text",
            ]) + "\n",
            encoding="utf-8",
        )
        print("[pkt-git] .gitattributes written (binary merge disabled, snapshot text enabled).")

    _git("config", "core.hooksPath", HOOK_DIR)
    _git("config", "pktgit.py", py)
    _git("config", "pktgit.script", script)

    ver = subprocess.run([py, "--version"], capture_output=True, text=True).stdout.strip()
    print(f"[pkt-git] wired: hooks in {hookdir}/ -> {script}")
    print(f"[pkt-git] interpreter: {ver}")
    print("[pkt-git] next step: import a project with")
    print("    pkt export my_project.pkt snapshot/my_project/")
    print("  and place the binary under topologia/my_project.pkt, then commit.")
    return 0


def cmd_version(_args: list[str]) -> int:
    """Print the CLI version."""
    print("pkt-git CLI v1.0")
    return 0


def main() -> int:
    """Dispatch argv to the subcommand table."""
    cmds = {
        "init": cmd_init,
        "export": cmd_export,
        "build": cmd_build,
        "inspect": cmd_inspect,
        "edit": cmd_edit,
        "sync": cmd_sync,
        "verify": cmd_verify,
        "pre-commit": cmd_pre_commit,
        "post-merge": cmd_post_merge,
        "post-checkout": cmd_post_checkout,
        "--version": cmd_version,
        "version": cmd_version,
    }
    if len(sys.argv) < 2 or sys.argv[1] not in cmds:
        print(__doc__)
        return 2
    return cmds[sys.argv[1]](sys.argv[2:])


if __name__ == "__main__":
    sys.exit(main())
