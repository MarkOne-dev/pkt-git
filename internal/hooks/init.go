// Package hooks wires pkt-git into a Git repository and implements the hook
// entry points that keep snapshots and binaries synchronized.
package hooks

import (
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/MarkOne-dev/pkt-git/internal/fsx"
	"github.com/MarkOne-dev/pkt-git/internal/gitx"
)

// ErrNotRepository reports that pkt init was run outside a Git work tree.
var ErrNotRepository = errors.New("not a git repository; run git init first")

const (
	// HookDir is the repository-local hooks directory.
	HookDir = ".githooks"
	// BinConfigKey stores the absolute path of the running pkt executable.
	BinConfigKey = "pktgit.bin"
	// HooksPathKey is the repository-local Git configuration key.
	HooksPathKey = "core.hooksPath"
)

var hookNames = []string{"pre-commit", "post-merge", "post-checkout"}

var requiredAttributes = []string{
	"*.pkt binary",
	"*.pka binary",
	"snapshot/**/base.snapshot.xml text",
	"snapshot/**/*.json text",
	"snapshot/**/*.cfg text",
}

const attributesHeader = "# pkt-git ownership: the binary is an artifact; the snapshot is the source of truth."

// InitResult describes what Init changed.
type InitResult struct {
	Root              string
	HookDir           string
	Executable        string
	HooksWritten      []string
	AttributesCreated bool
	AttributesAdded   []string
	AttributesChanged bool
}

// Init configures an existing Git repository. dir may be any path inside the
// work tree; an empty dir means the current directory. executable must be the
// pkt binary path; when empty, the running executable is used.
func Init(dir, executable string) (InitResult, error) {
	repo := gitx.New(dir)
	root, err := repo.Toplevel()
	if err != nil {
		return InitResult{}, fmt.Errorf("hooks: %w", ErrNotRepository)
	}

	if executable == "" {
		executable, err = os.Executable()
		if err != nil {
			return InitResult{}, fmt.Errorf("hooks: locate pkt executable: %w", err)
		}
	}
	executable, err = filepath.Abs(executable)
	if err != nil {
		return InitResult{}, fmt.Errorf("hooks: resolve executable path: %w", err)
	}
	// Hooks run under Git's POSIX shell, including on Windows; forward slashes
	// are accepted by both POSIX and Windows path handling.
	executable = filepath.ToSlash(executable)

	hookDir := filepath.Join(root, HookDir)
	if err := os.MkdirAll(hookDir, 0o755); err != nil {
		return InitResult{}, fmt.Errorf("hooks: create %s: %w", hookDir, err)
	}

	result := InitResult{
		Root:       root,
		HookDir:    hookDir,
		Executable: executable,
	}
	for _, name := range hookNames {
		path := filepath.Join(hookDir, name)
		if err := fsx.WriteFileAtomic(path, []byte(hookBody(name)), 0o755); err != nil {
			return InitResult{}, fmt.Errorf("hooks: write %s: %w", path, err)
		}
		result.HooksWritten = append(result.HooksWritten, name)
	}

	created, added, changed, err := mergeAttributes(root)
	if err != nil {
		return InitResult{}, err
	}
	result.AttributesCreated = created
	result.AttributesAdded = added
	result.AttributesChanged = changed

	if err := repo.ConfigSet(HooksPathKey, HookDir); err != nil {
		return InitResult{}, fmt.Errorf("hooks: set %s: %w", HooksPathKey, err)
	}
	if err := repo.ConfigSet(BinConfigKey, executable); err != nil {
		return InitResult{}, fmt.Errorf("hooks: set %s: %w", BinConfigKey, err)
	}
	return result, nil
}

func hookBody(name string) string {
	return "#!/bin/sh\n" +
		"# Generated by pkt init. Do not edit.\n" +
		`exec "$(git config --get ` + BinConfigKey + ` || command -v pkt)" ` + name + ` "$@"` + "\n"
}

func mergeAttributes(root string) (created bool, added []string, changed bool, err error) {
	path := filepath.Join(root, ".gitattributes")
	data, readErr := os.ReadFile(path)
	if readErr != nil && !errors.Is(readErr, os.ErrNotExist) {
		return false, nil, false, fmt.Errorf("hooks: read %s: %w", path, readErr)
	}
	created = errors.Is(readErr, os.ErrNotExist)

	content := string(data)
	present := make(map[string]bool)
	for _, line := range strings.Split(content, "\n") {
		trimmed := strings.TrimSpace(line)
		if trimmed == "" || strings.HasPrefix(trimmed, "#") {
			continue
		}
		present[normalizeRule(trimmed)] = true
	}

	for _, rule := range requiredAttributes {
		if present[normalizeRule(rule)] {
			continue
		}
		added = append(added, rule)
	}

	if !created && len(added) == 0 {
		return false, nil, false, nil
	}

	if content != "" && !strings.HasSuffix(content, "\n") {
		content += "\n"
	}
	if content == "" || !strings.Contains(content, attributesHeader) {
		content += attributesHeader + "\n"
	}
	for _, rule := range added {
		content += rule + "\n"
	}

	if err := fsx.WriteFileAtomic(path, []byte(content), 0); err != nil {
		return false, nil, false, fmt.Errorf("hooks: write %s: %w", path, err)
	}
	return created, added, true, nil
}

func normalizeRule(rule string) string {
	return strings.Join(strings.Fields(rule), " ")
}
